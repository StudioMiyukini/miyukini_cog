//! A tiny 5x7 bitmap font rendered as coloured quads. No external font assets:
//! each glyph is a 7-row bitmask (5 columns, bit 4 = leftmost), and runs of set
//! pixels in a row are coalesced into a single quad to keep the batch small.

use mge_render::batch::{RenderLayer, SortKey, SpriteBatch, SpriteInstance};

use super::vertex::Color;
use super::{ATLAS, MAT, UNIT};

/// Width of one character cell as a multiple of the pixel size (5 cols + gap).
pub const CELL: f32 = 6.0;

/// Total pixel width a string occupies at pixel size `px`.
#[must_use]
#[allow(clippy::cast_precision_loss)]
pub fn text_width(text: &[u8], px: f32) -> f32 {
    text.len() as f32 * CELL * px
}

/// Draw `text` at screen `(x, y)` with per-dot pixel size `px`. Returns width.
#[allow(clippy::cast_precision_loss, clippy::too_many_arguments)]
pub fn draw_text(
    batch: &mut SpriteBatch,
    text: &[u8],
    x: f32,
    y: f32,
    px: f32,
    color: Color,
    layer: RenderLayer,
    y_sort: i32,
    sub: u32,
) -> f32 {
    let char_w = CELL * px;
    for (ci, &ch) in text.iter().enumerate() {
        let rows = glyph(ch);
        let cx = x + ci as f32 * char_w;
        for (row, &bits) in rows.iter().enumerate() {
            if bits == 0 {
                continue;
            }
            let ry = y + row as f32 * px;
            let mut col = 0u8;
            while col < 5 {
                if bits & (0x10 >> col) != 0 {
                    let start = col;
                    while col < 5 && bits & (0x10 >> col) != 0 {
                        col += 1;
                    }
                    let rx = cx + f32::from(start) * px;
                    let rw = f32::from(col - start) * px;
                    batch.push(SpriteInstance {
                        screen_pos: [rx, ry],
                        src: UNIT,
                        atlas: ATLAS,
                        material: MAT,
                        sort_key: SortKey { layer, y_sort, sub_order: sub },
                        tint: color,
                        scale: [rw, px],
                    });
                } else {
                    col += 1;
                }
            }
        }
    }
    text.len() as f32 * char_w
}

/// Draw centred text; returns the left x used.
#[allow(clippy::too_many_arguments)]
pub fn draw_text_centered(
    batch: &mut SpriteBatch,
    text: &[u8],
    cx: f32,
    y: f32,
    px: f32,
    color: Color,
    layer: RenderLayer,
    y_sort: i32,
    sub: u32,
) -> f32 {
    let w = text_width(text, px);
    let x = cx - w * 0.5;
    draw_text(batch, text, x, y, px, color, layer, y_sort, sub);
    x
}

/// Format a non-negative integer into a stack buffer; returns `(buf, len)`.
#[must_use]
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
pub fn fmt_u32(v: u32) -> ([u8; 12], usize) {
    let mut buf = [0u8; 12];
    if v == 0 {
        buf[0] = b'0';
        return (buf, 1);
    }
    let mut tmp = [0u8; 12];
    let mut n = v;
    let mut i = 12;
    while n > 0 {
        i -= 1;
        tmp[i] = b'0' + (n % 10) as u8;
        n /= 10;
    }
    let len = 12 - i;
    buf[..len].copy_from_slice(&tmp[i..]);
    (buf, len)
}

/// 5x7 glyph bitmask for a byte. Unknown bytes render as a filled box.
