#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lowercase_maps_to_uppercase() {
        assert_eq!(glyph(b'a'), glyph(b'A'));
    }

    #[test]
    fn space_is_blank() {
        assert_eq!(glyph(b' '), [0; 7]);
    }

    #[test]
    fn fmt_u32_basic() {
        let (b, n) = fmt_u32(0);
        assert_eq!(&b[..n], b"0");
        let (b, n) = fmt_u32(1234);
        assert_eq!(&b[..n], b"1234");
    }

    #[test]
    fn width_scales_with_len() {
        assert!((text_width(b"AB", 2.0) - 2.0 * CELL * 2.0).abs() < 1e-6);
    }
}
